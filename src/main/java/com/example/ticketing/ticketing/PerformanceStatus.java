package com.example.ticketing.ticketing;

public enum PerformanceStatus {
    /**
     * 1. 공연 준비 중 (기획 단계)
     * - 공연 정보(출연진, 장소 등)를 입력하고 있는 단계입니다.
     * - 아직 사용자에게 노출되지 않거나, '오픈 예정'으로 표시됩니다.
     */
    PREPARING,

    /**
     * 2. 예매 활성화 (판매 중)
     * - 티켓 오픈 시간이 지나고 실제 사용자가 좌석을 선택하고 예매할 수 있는 상태입니다.
     * - 사용자 화면에 '예매하기' 버튼이 활성화됩니다.
     */
    PREPARED,

    /**
     * 3. 판매 일시 중지 또는 강제 마감
     * - 공연 당일 직전이나 특정 사유로 인해 더 이상 예매를 받지 않는 상태입니다.
     * - 좌석이 남아있더라도 시스템적으로 신규 예매를 차단합니다.
     */
    TERMINATED,

    /**
     * 4. 공연 종료
     * - 공연 시간이 종료되어 모든 절차가 마무리된 상태입니다.
     * - 이 상태의 공연은 대개 '지난 공연' 목록으로 이동합니다.
     */
    COMPLETED,

    /**
     * 5. 공연 취소
     * - 주최측의 사정이나 천재지변 등으로 공연 자체가 무산된 상태입니다.
     * - 이 상태가 되면 기존 예매자들에게 일괄 환불 처리가 진행되어야 합니다.
     */
    CANCELLED
}